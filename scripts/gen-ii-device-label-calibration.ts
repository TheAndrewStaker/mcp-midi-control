/**
 * gen-ii-device-label-calibration.ts: emit the Axe-Fx II device-label
 * calibration table from the fitter's accepted proposals.
 *
 *   npx tsx scripts/_research/ii-label-fit.ts            # corpus -> proposals
 *   npx tsx scripts/gen-ii-device-label-calibration.ts   # proposals -> generated TS
 *
 * Every entry is backed by the II's own rendered labels (fn 0x02 GET replies,
 * read-only sweep of stored presets plus write-and-restore probes for params
 * the presets never varied): the model prints every observed label exactly.
 * See scripts/_research/ii-label-fit.ts for the acceptance rule.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const IN = process.argv[2] ?? 'samples/captured/ii-label-proposals.json';
const OUT = 'packages/fractal-midi/src/gen2/axe-fx-ii/deviceLabelCalibration.generated.ts';

interface Model { scale: 'linear' | 'log10' | 'ordinal'; min: number; max: number; offset?: number; factor?: number; from: string }
interface Proposal { key: string; verdict: string; model?: Model; unit?: string; labels?: Record<number, string>; rounding?: string; sigFigs?: number; decimals?: number; samples: number; distinctWires: number; currentHits: number }
interface EnumProposal { key: string; verdict: string; values?: string[]; samples: number; from?: string }
const { numeric, enums } = JSON.parse(readFileSync(IN, 'utf8')) as { numeric: Proposal[]; enums: EnumProposal[] };

const rows = numeric.filter((p) => p.verdict === 'accept' && p.model).sort((a, b) => a.key.localeCompare(b.key));
const enumRows = enums.filter((e) => (e.verdict === 'fill' || e.verdict === 'fix') && e.values).sort((a, b) => a.key.localeCompare(b.key));

const lines: string[] = [];
lines.push('// GENERATED by scripts/gen-ii-device-label-calibration.ts. Do not edit by hand.');
lines.push('/**');
lines.push(' * Axe-Fx II display calibration measured against the device\'s OWN labels.');
lines.push(' *');
lines.push(' * The II renders its display text into every fn 0x02 GET reply. Each entry');
lines.push(' * below prints every label observed for that param (XL+, Ares 2.00) within');
lines.push(' * the label\'s last digit: a read-only sweep of the stored presets, plus');
lines.push(' * write-and-restore probes where the presets never varied a param. The');
lines.push(' * range/taper is the Axe-Edit editor-cache record for the param where that');
lines.push(' * record fits the labels, else a least-squares fit of the labels themselves.');
lines.push(' * `samples` / `distinctWires` are the evidence counts.');
lines.push(' */');
lines.push('export interface DeviceLabelCalibration {');
lines.push('  readonly scale: \'linear\' | \'log10\' | \'ordinal\';');
lines.push('  readonly displayMin: number;');
lines.push('  readonly displayMax: number;');
lines.push('  /** ordinal only: display = wire * (factor ?? 1) + offset */');
lines.push('  readonly offset?: number;');
lines.push('  readonly factor?: number;');
lines.push('  /** words the device prints at specific wires instead of a number ("INFINITE", "OFF") */');
lines.push('  readonly labels?: Readonly<Record<number, string>>;');
lines.push('  /** unit word the device prints (hz, ms, seconds, db, percent, bipolar_percent, degrees, pf) */');
lines.push('  readonly unit?: string;');
lines.push("  /** 'truncate': the device cuts to `decimals` toward zero instead of rounding to nearest */");
lines.push("  readonly rounding?: 'truncate';");
lines.push('  /** print this many significant figures (decimals then caps the digits after the point) */');
lines.push('  readonly sigFigs?: number;');
lines.push('  /** digits after the point the device prints */');
lines.push('  readonly decimals: number;');
lines.push('  readonly samples: number;');
lines.push('  readonly distinctWires: number;');
lines.push('  readonly from: string;');
lines.push('}');
lines.push('');
lines.push('export const DEVICE_LABEL_CALIBRATION: Readonly<Record<string, DeviceLabelCalibration>> = Object.freeze({');
for (const r of rows) {
  const m = r.model!;
  const parts = [`scale: '${m.scale}'`, `displayMin: ${m.min}`, `displayMax: ${m.max}`];
  if (m.scale === 'ordinal') { parts.push(`offset: ${m.offset}`); if (m.factor !== undefined) parts.push(`factor: ${m.factor}`); }
  if (r.unit) parts.push(`unit: '${r.unit}'`);
  if (r.labels && Object.keys(r.labels).length) parts.push(`labels: { ${Object.entries(r.labels).map(([w, t]) => `${w}: ${JSON.stringify(t)}`).join(', ')} }`);
  if (r.rounding) parts.push(`rounding: '${r.rounding}'`);
  if (r.sigFigs) parts.push(`sigFigs: ${r.sigFigs}`);
  parts.push(`decimals: ${r.decimals ?? 2}`, `samples: ${r.samples}`, `distinctWires: ${r.distinctWires}`, `from: '${m.from}'`);
  lines.push(`  '${r.key}': { ${parts.join(', ')} },`);
}
lines.push('});');
lines.push('');
lines.push('/** Enum rosters the device confirmed (every observed label equals the roster entry at its ordinal). */');
lines.push('export const DEVICE_LABEL_ENUMS: Readonly<Record<string, Readonly<Record<number, string>>>> = Object.freeze({');
for (const e of enumRows) {
  const body = e.values!.map((v, i) => `${i}: ${JSON.stringify(v.trim())}`).join(', ');
  lines.push(`  '${e.key}': Object.freeze({ ${body} }),`);
}
lines.push('});');
lines.push('');
writeFileSync(OUT, lines.join('\n'));
console.log(`${rows.length} numeric, ${enumRows.length} enum -> ${OUT}`);
