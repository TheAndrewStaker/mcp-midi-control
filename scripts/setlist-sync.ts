/**
 * setlist-sync.ts — rewrite a setlist's measured columns from the card capture,
 * leaving every hand-authored word alone.
 *
 * WHY THIS EXISTS. This rig's setlist carried a hand-maintained `Built?` column
 * that its own notes admit "was originally inferred and was WRONG three times".
 * On 2026-08-05 it was wrong a fourth time, on TEN of seventeen rows: nine said
 * `no` and one said `planned, next up` while the card held complete builds for
 * all ten, including one full 16-project song. A hand-kept column mirroring a
 * derivable fact drifts silently; the fix is not another careful pass, it is to
 * stop hand-keeping it.
 *
 * SO THE COLUMN IS SPLIT, and ownership is explicit:
 *
 *   `On card`      GENERATED. Measured from the newest card capture every run.
 *                  Never hand-edit it; this script overwrites it.
 *   `Ear-checked`  YOURS. Never written except to seed a new row as `?`.
 *                  Preserved verbatim, matched by song, across every run.
 *
 * The split exists because the two facts are genuinely different and conflating
 * them is what made the old column untrustworthy: projects being ON THE CARD
 * says nothing about whether they have been heard and approved. One song has eight
 * projects and its own doc says "Nothing has been signed off by ear yet."
 *
 * WHAT IT WILL NOT DO. It never invents an ear-check, never reorders the set,
 * never adds or removes a song, and never touches prose. A new row seeds as `?`
 * rather than inheriting the old `Built?` value, because importing a column that
 * was wrong ten times would launder those errors into the column that is
 * supposed to be trustworthy.
 *
 * USAGE
 *   npm run setlist-sync                 # rewrite the newest setlist
 *   npm run setlist-sync -- --check      # report drift, write nothing, exit 1 if stale
 *   npx tsx scripts/setlist-sync.ts --setlist <file> --capture <dir>
 *
 * TOUCHES NO HARDWARE. Reads a capture, rewrites one markdown table.
 */
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';

import {
  joinSongs, latestCapture, latestSetlist, loadCard, parseSetlist, songKey,
  type ConsoleSong,
} from './_lib/console-sources.js';

const argv = process.argv.slice(2);
const flag = (n: string): string | undefined => { const i = argv.indexOf(n); return i === -1 ? undefined : argv[i + 1]; };
const CHECK = argv.includes('--check');
const SETLIST = flag('--setlist') ?? latestSetlist();
const CAPTURE = flag('--capture') ?? latestCapture();

/** The generated cell: what the capture holds, in the rig's own P<pack>:<slots> shorthand. */
function onCardCell(s: ConsoleSong): string {
  if (!s.on_card) return 'nothing on the card';
  const where = s.where.replace(/Pack (\d+) projects? /g, 'P$1:');
  return `${s.project_count} project${s.project_count === 1 ? '' : 's'}, ${where}`;
}

const HEADER = '| # | Song | Artist | On card | Ear-checked |';
const RULE = '|---|---|---|---|---|';
const OWNERSHIP = [
  '<!-- `On card` is GENERATED by `npm run setlist-sync` from the newest card capture.',
  '     Do not hand-edit it; the next run overwrites it.',
  '     `Ear-checked` is YOURS. The generator only ever seeds a new row as `?`. -->',
].join('\n');

const NOT_IN_SET_HEADING = '## On the card, deliberately not in the set';

/**
 * Replace one `## ` section's body, or insert the section before `anchor`.
 *
 * Line-based on purpose. The first cut used
 * `/^## Heading\n[\s\S]*?(?=^## |$)/m` and was NOT idempotent: under the `m`
 * flag `$` matches end-of-LINE, so the lazy body matched almost nothing, the
 * old section survived, and every run appended another copy. Three duplicate
 * tables before it was caught. A section rewrite is a line-scan problem, not a
 * regex problem.
 */
function replaceSection(doc: string, heading: string, body: string, anchor: string): string {
  const lines = doc.split('\n');
  const isHeading = (l: string): boolean => l.startsWith('## ');
  const start = lines.findIndex((l) => l.trim() === heading);

  if (start === -1) {
    const at = lines.findIndex((l) => l.trim() === anchor);
    const block = [...body.split('\n'), ''];
    if (at === -1) return [...lines, '', ...block].join('\n');
    return [...lines.slice(0, at), ...block, ...lines.slice(at)].join('\n');
  }

  let end = start + 1;
  while (end < lines.length && !isHeading(lines[end])) end++;
  return [...lines.slice(0, start), ...body.split('\n'), '', ...lines.slice(end)].join('\n');
}

function main(): void {
  if (SETLIST === undefined) { console.error('No setlist found under docs/_private/rig/setlists.'); process.exit(1); }
  const { card } = loadCard(CAPTURE);
  if (card === undefined) { console.error(`No card capture found (looked at ${CAPTURE ?? 'samples/circuit-ncs'}).`); process.exit(1); }

  const original = readFileSync(SETLIST, 'utf8');
  const entries = parseSetlist(original);
  if (entries.length === 0) { console.error(`No song table found in ${SETLIST}.`); process.exit(1); }
  const join = joinSongs(entries, card);
  const inSet = join.songs.filter((s) => s.position !== undefined).sort((a, b) => a.position! - b.position!);

  // Preserve the maintainer's ear-checks, matched by song rather than by row
  // index, so a reorder cannot shift them onto the wrong songs.
  const kept = new Map(entries.map((e) => [songKey(e.title), e.ear_checked]));

  const rows = inSet.map((s) => {
    const ear = kept.get(songKey(s.title));
    return `| ${s.position} | ${s.title} | ${s.artist ?? ''} | ${onCardCell(s)} | ${ear === undefined || ear === '' ? '?' : ear} |`;
  });

  const table = [OWNERSHIP, '', HEADER, RULE, ...rows].join('\n');

  // Replace everything between the order heading and the next heading.
  const orderRe = /(^## The order\s*\n)([\s\S]*?)(?=^## )/m;
  if (!orderRe.test(original)) { console.error(`Could not find a "## The order" section in ${SETLIST}.`); process.exit(1); }
  let next = original.replace(orderRe, (_m, heading: string) => `${heading}${table}\n\n`);

  // The card-only section: songs the card holds that the set does not list.
  // Reported as a section rather than dropped, so an absence is a visible
  // decision rather than an oversight.
  const cardOnly = join.songs.filter((s) => s.position === undefined)
    .sort((a, b) => a.title.localeCompare(b.title));
  if (cardOnly.length > 0) {
    // A hand-written NOTE on a card-only row is the maintainer's ruling on why a
    // song is off the set, so it is preserved across runs exactly like an
    // ear-check. Matched by song, not by row order.
    const keptNotes = new Map<string, string>();
    for (const m of next.matchAll(/^\|\s*([^|]+?)\s*\|[^|]*\|[^|]*\|\s*([^|]*?)\s*\|\s*$/gm)) {
      const note = m[2].trim();
      if (note !== '') keptNotes.set(songKey(m[1]), note);
    }
    const body = [
      NOT_IN_SET_HEADING,
      '',
      '<!-- GENERATED by `npm run setlist-sync`. The NOTE column is yours; the rest is measured. -->',
      '',
      '| Song | Artist | On card | Note |',
      '|---|---|---|---|',
      ...cardOnly.map((s) =>
        `| ${s.title} | ${s.artist ?? ''} | ${onCardCell(s)} | ${keptNotes.get(songKey(s.title)) ?? cardOnlyNote(s.title)} |`),
    ].join('\n');
    next = replaceSection(next, NOT_IN_SET_HEADING, body, '## Read with care');
  }

  if (next === original) { console.log('Already in sync; nothing written.'); return; }
  if (CHECK) {
    console.log(`STALE: ${SETLIST} does not match the capture. Run: npm run setlist-sync`);
    process.exit(1);
  }

  const backup = `${SETLIST}.${new Date().toISOString().replace(/[:.]/g, '-')}.bak`;
  copyFileSync(SETLIST, backup);
  writeFileSync(SETLIST, next, 'utf8');

  console.log(`synced ${SETLIST}`);
  console.log(`  backup: ${backup}`);
  console.log(`  capture: ${card.captured_at}`);
  console.log(`  ${inSet.length} songs in the set, ${cardOnly.length} on the card but not in it`);
  const seeded = inSet.filter((s) => { const e = kept.get(songKey(s.title)); return e === undefined || e === ''; });
  if (seeded.length > 0) console.log(`  ${seeded.length} row(s) seeded Ear-checked = "?" (never invented)`);
  const missing = inSet.filter((s) => !s.on_card);
  if (missing.length > 0) console.log(`  ! ${missing.length} song(s) in the set with nothing on the card: ${missing.map((s) => s.title).join(', ')}`);
}

/**
 * The note on a card-only row. Only the songs the maintainer has actually ruled
 * on are stated; anything else is left blank for him rather than guessed. The
 * rulings are his data, so they live beside the private rig files as a JSON map
 * of song key to note, not in this script. No file means no notes.
 */
const CARD_ONLY_NOTES_FILE = 'docs/_private/rig/setlist-card-only-notes.json';
function cardOnlyNote(title: string): string {
  if (!existsSync(CARD_ONLY_NOTES_FILE)) return '';
  const notes = JSON.parse(readFileSync(CARD_ONLY_NOTES_FILE, 'utf8')) as Record<string, string>;
  return notes[songKey(title)] ?? '';
}

main();
